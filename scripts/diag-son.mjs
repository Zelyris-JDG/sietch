import { chromium } from "@playwright/test";
const browser = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push("PAGEERROR " + e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push("CONSOLE " + m.text().slice(0, 200)); });
await page.goto("http://127.0.0.1:3100/?monde=calme", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Entrer avec le son" }).click();
await page.waitForTimeout(1500);
const btn = page.getByRole("button", { name: /Son coupé : activer|Son : couper/ });
console.log("bouton après intro :", await btn.getAttribute("aria-pressed"), "| pref :", await page.evaluate(() => localStorage.getItem("sietch-son")));
await page.evaluate(() => window.scrollTo({ top: 3000, behavior: "instant" }));
await page.waitForTimeout(1200);
await btn.click();
await page.waitForTimeout(600);
console.log("après clic :", await btn.getAttribute("aria-pressed"), "| pref :", await page.evaluate(() => localStorage.getItem("sietch-son")));
await page.reload({ waitUntil: "networkidle" });
await page.waitForTimeout(500);
console.log("après rechargement (intro déjà vue ?) :", await page.locator(".intro").count(), "| pref :", await page.evaluate(() => localStorage.getItem("sietch-son")));
console.log("erreurs :", errors.length ? errors.join("\n") : "aucune");
await browser.close();
